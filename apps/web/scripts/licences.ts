/**
 * Writes src/licences.ts: the libraries Seijaku depends on and their licences, for Settings → About.
 * Run from the repo root after changing dependencies: bun apps/web/scripts/licences.ts
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..", "..", "..");
const manifests = [
	"apps/web/package.json",
	"apps/server/package.json",
	"packages/sync/package.json",
	"packages/db/package.json",
];

const names = new Set<string>();
for (const m of manifests) {
	const json = JSON.parse(readFileSync(join(root, m), "utf8")) as {
		dependencies?: Record<string, string>;
	};
	for (const n of Object.keys(json.dependencies ?? {}))
		if (!n.startsWith("@seijaku/")) names.add(n);
}

function find(name: string): string | null {
	for (const base of [
		"apps/web",
		"apps/server",
		"packages/sync",
		"packages/db",
		".",
	]) {
		const p = join(root, base, "node_modules", name, "package.json");
		if (existsSync(p)) return p;
	}
	return null;
}

const rows = [...names].sort().map((name) => {
	const p = find(name);
	const pkg = p
		? (JSON.parse(readFileSync(p, "utf8")) as {
				license?: string;
				version?: string;
			})
		: {};
	return [name, pkg.version ?? "", pkg.license ?? "see package"] as const;
});

writeFileSync(
	join(root, "apps/web/src/licences.ts"),
	`// Generated by apps/web/scripts/licences.ts. Do not edit by hand.\nexport const LICENCES: readonly (readonly [name: string, version: string, licence: string])[] = ${JSON.stringify(rows, null, "\t")};\n`,
);
console.log(`${rows.length} libraries`);
