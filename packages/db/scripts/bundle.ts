import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Turns the folders drizzle-kit writes (drizzle/<set>/<time>_<name>/migration.sql) into one
 * TypeScript module, so every runtime can apply them without a file system: Bun, a Durable
 * Object and D1 all import the same object. Run through `bun run db:generate`.
 */
const root = join(import.meta.dir, "..");
let out = `// Generated by scripts/bundle.ts from drizzle/. Do not edit by hand.\n\n`;
for (const set of ["log", "account"]) {
	const dir = join(root, "drizzle", set);
	const folders = readdirSync(dir, { withFileTypes: true })
		.filter((d) => d.isDirectory())
		.map((d) => d.name)
		.sort();
	out += `/** Migration name to SQL, statements separated by \`--> statement-breakpoint\`. */\n`;
	out += `export const ${set}Migrations: Record<string, string> = {\n`;
	for (const name of folders) {
		const sql = readFileSync(join(dir, name, "migration.sql"), "utf8");
		out += `\t${JSON.stringify(name)}: ${JSON.stringify(sql)},\n`;
	}
	out += `};\n\n`;
}
writeFileSync(join(root, "src", "migrations.ts"), out.trimEnd() + "\n");
